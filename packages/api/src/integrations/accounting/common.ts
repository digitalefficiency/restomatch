import type { AccountingConfig, AccountingInvoice } from './types';

/** NUMERIC(12,2) string (Drizzle) → integer agorot, exact (no float math). */
export function numericToAgorot(value: string | number | null | undefined): number | null {
  if (value === null || value === undefined || value === '') return null;
  const s = String(value).trim();
  const m = /^(-)?(\d+)(?:\.(\d{1,}))?$/.exec(s);
  if (!m) return null;
  const frac = (m[3] ?? '').padEnd(3, '0');
  // Half-up on the third decimal, in case a NUMERIC(12,4) value is passed.
  let agorot = Number(m[2]) * 100 + Number(frac.slice(0, 2)) + (Number(frac[2]) >= 5 ? 1 : 0);
  if (m[1]) agorot = -agorot;
  return agorot;
}

/** Integer agorot → `1234.50` (dot decimal, no grouping): what import files expect. */
export function agorotToPlain(agorot: number): string {
  const sign = agorot < 0 ? '-' : '';
  const a = Math.abs(agorot);
  return `${sign}${Math.floor(a / 100)}.${String(a % 100).padStart(2, '0')}`;
}

/** `YYYY-MM-DD` → `DD/MM/YYYY` (or `DD/MM/YY`). */
export function ddmmyyyy(isoDate: string, shortYear = false): string {
  const [y, m, d] = isoDate.split('-');
  return `${d}/${m}/${shortYear ? y!.slice(2) : y}`;
}

/**
 * Supplier card code: explicit mapping → company id (ח״פ) digits → none.
 * A code is NEVER invented (W2-14, admin-10): an invented `S…` card posted the
 * purchase to a card that doesn't exist in the books. `null` = no card; the
 * invoice is left out of the file and counted (`renderAccountingFile`).
 */
export function supplierAccountOrNull(inv: AccountingInvoice, cfg: AccountingConfig): string | null {
  const mapped = inv.supplierId ? cfg.supplierAccounts[inv.supplierId]?.trim() : undefined;
  if (mapped) return mapped;
  const digits = inv.supplierBusinessId.replace(/\D/g, '');
  return digits || null;
}

/** The card code of an invoice the renderer was given (only mapped ones reach it). */
export function supplierAccount(inv: AccountingInvoice, cfg: AccountingConfig): string {
  return supplierAccountOrNull(inv, cfg) ?? '';
}

/**
 * Tabs/newlines inside a value would break a delimited record. Truncation
 * counts code points, so an emoji (a surrogate pair) is never cut in half.
 */
export function cell(value: string, max?: number): string {
  const clean = value.replace(/[\t\r\n]+/g, ' ').trim();
  return max ? Array.from(clean).slice(0, max).join('') : clean;
}

/**
 * Spreadsheet formula injection: an accountant opens these files in Excel to
 * check them, and a cell that starts with = + - @ runs as a formula. Supplier
 * names and invoice numbers come from OCR / user input, so every TEXT cell gets
 * a leading apostrophe when it starts with one of those. (Amount cells are
 * generated by us and never pass through here.)
 */
export function safeCell(value: string, max?: number): string {
  const v = cell(value, max);
  return /^[=+\-@]/.test(v) ? `'${max ? Array.from(v).slice(0, max - 1).join('') : v}` : v;
}

