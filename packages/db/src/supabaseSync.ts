import { createHash } from 'node:crypto';
import { existsSync, readdirSync, readFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { migrationHash, migrationsDir, readJournal, REQUIRED_EXTENSIONS } from './migrations';
import { rlsAppRoleGrantsSql } from './rls';

/**
 * Drizzle → Supabase migrations (`pnpm db:supabase-sync`).
 *
 * Drizzle (packages/db/drizzle + meta/_journal.json) stays the single source of
 * truth. Supabase's GitHub integration applies `supabase/migrations/<version>_<name>.sql`
 * files whose 14-digit version it has not recorded yet (supabase_migrations.schema_migrations),
 * in version order, on a push/merge to the project's production branch. This
 * module derives that directory from the journal:
 *
 *   <first-1s>_restomatch_bootstrap.sql   extensions exactly as scripts/migrate.ts creates
 *                                         them + the drizzle tracker table
 *   <when>_<tag>.sql                      one per journal entry: the drizzle SQL verbatim
 *                                         + an idempotent tracker row (hash/created_at as
 *                                         drizzle-orm records them), so `pnpm db:migrate`
 *                                         and `db:doctor` see the database as migrated
 *   <tail+1s>_restomatch_rls_<hash8>.sql  provision-rls as a migration: rls/0002 + rls/0003,
 *                                         restomatch_app (NOLOGIN, no password in git) +
 *                                         ensureRlsAppRole's grants, the private
 *                                         `invoice-scans` bucket and rls/0001 storage policies
 *
 * The RLS file is idempotent and re-emitted (new, later version) whenever its
 * content changes or a newer journal entry lands, so a fresh table always gets
 * its policies and grants. Earlier RLS files are kept: Supabase has recorded
 * their versions, and the CLI rejects a remote history the repo no longer has.
 */

export const SUPABASE_DIR = 'supabase';
export const SUPABASE_MIGRATIONS_DIR = 'supabase/migrations';
/**
 * Lock manifest of every migration file that has been committed (and may already
 * be applied by Supabase — versions are recorded remotely and never re-run).
 * The generator only ever APPENDS: a locked file that is missing or whose bytes
 * changed is an error, never something it "fixes" by rewriting.
 */
export const SUPABASE_LOCK = 'supabase/released-migrations.json';
const RLS_FILE_RE = /^(\d{14})_restomatch_rls_([0-9a-f]{8})\.sql$/;
const GENERATED_MARK = '-- Generated by `pnpm db:supabase-sync`';

export function repoRoot(): string {
  return join(dirname(fileURLToPath(import.meta.url)), '..', '..', '..');
}

/** Drizzle journal `when` (ms) → Supabase version (UTC YYYYMMDDHHMMSS). */
export function supabaseVersion(ms: number): string {
  return new Date(ms).toISOString().replace(/\D/g, '').slice(0, 14);
}

function versionToMs(version: string): number {
  const m = /^(\d{4})(\d{2})(\d{2})(\d{2})(\d{2})(\d{2})$/.exec(version);
  if (!m) throw new Error(`bad supabase version ${version}`);
  return Date.UTC(+m[1]!, +m[2]! - 1, +m[3]!, +m[4]!, +m[5]!, +m[6]!);
}

export const CONFIG_TOML = `${GENERATED_MARK.replace('-- ', '# ')} — minimal project config for the
# Supabase GitHub integration / CLI. The schema itself lives in packages/db/drizzle;
# supabase/migrations is generated from it (docs/SUPABASE-GITHUB-DEPLOY.md).
project_id = "restomatch"

[db]
port = 54322
shadow_port = 54320
major_version = 17

[db.seed]
# Never seed a real project from git: demo data is loaded explicitly (docs/DB-RUNBOOK.md).
enabled = false
`;

function bootstrapSql(): string {
  return `${GENERATED_MARK} — DO NOT EDIT.
-- Runs before the first drizzle migration. Mirrors scripts/migrate.ts: the same
-- extensions created the same way (no explicit schema, so they resolve exactly as
-- they do in production today), then the drizzle tracker table, so the database
-- is usable by \`pnpm db:migrate\` / \`db:doctor\` after a git deploy.
${REQUIRED_EXTENSIONS.map((e) => `create extension if not exists "${e}";`).join('\n')}

create schema if not exists drizzle;
create table if not exists drizzle.__drizzle_migrations (
  id serial primary key,
  hash text not null,
  created_at bigint
);
`;
}

function migrationSql(tag: string, idx: number, when: number, dir: string): string {
  const original = readFileSync(join(dir, `${tag}.sql`), 'utf8');
  const hash = migrationHash(tag, dir);
  const body = original.trimEnd();
  const terminated = body === '' || body.endsWith(';') ? body : `${body};`;
  return `${GENERATED_MARK} from packages/db/drizzle/${tag}.sql — DO NOT EDIT.
-- Drizzle journal idx ${idx}, when ${when}. The SQL below is the drizzle file verbatim;
-- the final INSERT records it in drizzle.__drizzle_migrations exactly as drizzle-orm would.
${terminated}

insert into drizzle.__drizzle_migrations (hash, created_at)
select '${hash}', ${when}
where not exists (select 1 from drizzle.__drizzle_migrations where created_at = ${when});
`;
}

const STORAGE_ALTER = 'alter table storage.objects enable row level security;';

export function rlsSql(dir: string = migrationsDir()): string {
  const rls = (f: string) => readFileSync(join(dir, 'rls', f), 'utf8').trimEnd();
  const storage = rls('0001_invoice_scans_rls.sql');
  if (!storage.includes(STORAGE_ALTER)) throw new Error('rls/0001 changed shape: update supabaseSync.ts');
  const storagePolicies = storage.replace(STORAGE_ALTER, '-- (RLS on storage.objects is enabled separately above)');
  if (storagePolicies.includes('$restomatch_storage$')) throw new Error('rls/0001 contains the dollar-quote tag');
  return `${GENERATED_MARK} — DO NOT EDIT. Idempotent; re-emitted after schema changes.
-- = \`pnpm --filter @restomatch/db provision-rls\` (PROVISION_STORAGE_RLS=1) as a migration.

-- 1. The non-owner tenant role. NOLOGIN and NO password in git: after the first
--    deploy the owner runs  ALTER ROLE restomatch_app WITH LOGIN PASSWORD '…';
--    (docs/SUPABASE-GITHUB-DEPLOY.md), or provision-rls with APP_ROLE_PASSWORD.
do $$ begin
  if not exists (select 1 from pg_roles where rolname = 'restomatch_app') then
    create role restomatch_app nologin;
  end if;
end $$;

-- 2. Core tenant RLS (packages/db/drizzle/rls/0002_core_tenant_rls.sql)
${rls('0002_core_tenant_rls.sql')}

-- 3. Append-only audit log (packages/db/drizzle/rls/0003_audit_immutable.sql)
${rls('0003_audit_immutable.sql')}

-- 4. Grants / revokes (packages/db/src/rls.ts → rlsAppRoleGrantsSql, same as ensureRlsAppRole)
${rlsAppRoleGrantsSql().trim()}

-- 5. Storage (Supabase): the private invoice-scans bucket the app uploads to,
--    then the storage.objects policies from rls/0001: the four per-restaurant
--    ones only. No anonymous access (SB-3): the former anon 'walk-ins/' showcase
--    policies are DROPPED here, since the showcase uploads server-side (service
--    role, POST /api/showcase/upload; SUPABASE-GITHUB-DEPLOY.md §SB-3). storage.objects
--    belongs to supabase_storage_admin; if the migration role may not alter it or
--    create policies on it, this logs a WARNING instead of failing the deploy —
--    apply rls/0001 from the SQL editor then (the doctor / verify-cutover report it).
do $$ begin
  if to_regclass('storage.buckets') is not null then
    -- SB-3: private, ≤11 MiB, invoice formats only (enforced by the Storage API).
    -- 11 MiB sits just above scans.upload's own cap (14M base64 chars ≈ 10.5 MB)
    -- so the app's friendly error fires first; HEIC/HEIF because the receiver
    -- picker accepts image/* and iPhones hand over HEIC from the photo library.
    insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
    values ('invoice-scans', 'invoice-scans', false, 11534336,
            array['application/pdf', 'image/jpeg', 'image/png', 'image/webp', 'image/heic', 'image/heif'])
    on conflict (id) do update set
      public = false,
      file_size_limit = excluded.file_size_limit,
      allowed_mime_types = excluded.allowed_mime_types;
  end if;
end $$;

do $restomatch_storage$ begin
  if to_regclass('storage.objects') is null then
    raise notice 'restomatch: no storage schema — skipping storage policies';
    return;
  end if;
  begin
    alter table storage.objects enable row level security;
  exception when insufficient_privilege then
    raise notice 'restomatch: storage.objects RLS not altered (%), Supabase enables it by default', sqlerrm;
  end;
  begin
    execute $policies$
${storagePolicies}
    $policies$;
  exception when insufficient_privilege then
    raise warning 'restomatch: storage.objects policies NOT applied as % (%) — run packages/db/drizzle/rls/0001_invoice_scans_rls.sql in the SQL editor', current_user, sqlerrm;
  end;
end $restomatch_storage$;

-- 6. Lock the Supabase Data API out of the schema. Supabase grants ALL on new
--    public tables/sequences to anon + authenticated by default privileges, and
--    those roles are reachable with the PUBLIC publishable key through PostgREST.
--    RestoMatch never reads tables through the Data API (supabase-js is used for
--    Storage only; all data goes through Drizzle), so they get nothing — otherwise
--    every table without RLS (plans, dsr_requests, the Auth.js identity tables)
--    would be readable/writable by anyone holding the publishable key.
do $$
declare r text;
begin
  foreach r in array array['anon', 'authenticated'] loop
    if exists (select 1 from pg_roles where rolname = r) then
      execute format('revoke all on all tables in schema public from %I', r);
      execute format('revoke all on all sequences in schema public from %I', r);
      execute format('alter default privileges in schema public revoke all on tables from %I', r);
      execute format('alter default privileges in schema public revoke all on sequences from %I', r);
    end if;
  end loop;
end $$;
`;
}

export interface SyncPlan {
  /** repo-relative path → content to write */
  writes: Map<string, string>;
  /** repo-relative paths that are up to date */
  unchanged: string[];
  /** generated-looking files under supabase/migrations that the plan no longer produces */
  orphans: string[];
}

/**
 * Compute the files `supabase/` must contain. Pure apart from reading the repo:
 * existing RLS files are kept (never rewritten) and decide whether a new one is due.
 */
export function planSupabaseSync(root: string = repoRoot(), dir: string = migrationsDir()): SyncPlan {
  const entries = readJournal(dir).entries;
  const migDir = join(root, SUPABASE_MIGRATIONS_DIR);
  const existing = new Map<string, string>();
  if (existsSync(migDir)) {
    for (const f of readdirSync(migDir)) {
      if (f.endsWith('.sql')) existing.set(f, readFileSync(join(migDir, f), 'utf8'));
    }
  }

  const lockPath = join(root, SUPABASE_LOCK);
  const lock: Record<string, string> = existsSync(lockPath) ? JSON.parse(readFileSync(lockPath, 'utf8')) : {};
  const sha = (body: string) => createHash('sha256').update(body).digest('hex');
  for (const [name, digest] of Object.entries(lock)) {
    const body = existing.get(name);
    if (body === undefined) throw new Error(`released migration ${name} is missing from ${SUPABASE_MIGRATIONS_DIR} — restore it byte-identical (git show origin/main:${SUPABASE_MIGRATIONS_DIR}/${name})`);
    if (sha(body) !== digest) throw new Error(`released migration ${name} was modified — released files are immutable; restore it and add a new migration instead`);
  }

  const want = new Map<string, string>();
  let prev = 0;
  for (const e of entries) {
    if (e.when - prev < 1000) throw new Error(`journal when values must increase by ≥1s (at ${e.tag})`);
    prev = e.when;
  }
  want.set(`${supabaseVersion(entries[0]!.when - 1000)}_restomatch_bootstrap.sql`, bootstrapSql());
  for (const e of entries) {
    want.set(`${supabaseVersion(e.when)}_${e.tag}.sql`, migrationSql(e.tag, e.idx, e.when, dir));
  }

  // A released file is never rewritten: if regenerating it gives different bytes,
  // its drizzle source was edited after release — that needs a NEW migration.
  for (const [name, body] of want) {
    if (lock[name] !== undefined && sha(body) !== lock[name]) {
      throw new Error(`${name} is released but its drizzle source changed — never edit an applied migration; add a new one`);
    }
  }

  // Out-of-order guard: a NEW file older than something already in the repo would
  // be skipped (or refused) by Supabase, exactly like the drizzle journal-gap problem.
  const maxExisting = [...existing.keys()].map((f) => f.slice(0, 14)).sort().pop();
  for (const name of want.keys()) {
    if (!existing.has(name) && maxExisting && name.slice(0, 14) <= maxExisting) {
      throw new Error(
        `${name} would be older than ${maxExisting} already in ${SUPABASE_MIGRATIONS_DIR} — Supabase would not apply it. Give the drizzle migration a later \`when\`.`,
      );
    }
  }

  // RLS: keep history; add a new file when the content changed or a newer migration landed.
  const content = rlsSql(dir);
  const hash8 = createHash('sha256').update(content).digest('hex').slice(0, 8);
  const rlsExisting = [...existing.keys()].filter((f) => RLS_FILE_RE.test(f)).sort();
  for (const f of rlsExisting) want.set(f, existing.get(f)!);
  const latest = rlsExisting.at(-1);
  const tailMs = entries.at(-1)!.when;
  const latestOk =
    latest && RLS_FILE_RE.exec(latest)![2] === hash8 && versionToMs(latest.slice(0, 14)) > tailMs;
  if (!latestOk) {
    const after = Math.max(tailMs, latest ? versionToMs(latest.slice(0, 14)) : 0);
    want.set(`${supabaseVersion(after + 1000)}_restomatch_rls_${hash8}.sql`, content);
  }

  const writes = new Map<string, string>();
  const unchanged: string[] = [];
  const add = (rel: string, body: string, current: string | undefined) => {
    if (current === body) unchanged.push(rel);
    else writes.set(rel, body);
  };
  const cfg = join(root, SUPABASE_DIR, 'config.toml');
  add(`${SUPABASE_DIR}/config.toml`, CONFIG_TOML, existsSync(cfg) ? readFileSync(cfg, 'utf8') : undefined);
  for (const [name, body] of want) add(`${SUPABASE_MIGRATIONS_DIR}/${name}`, body, existing.get(name));
  const orphans = [...existing.keys()]
    .filter((f) => !want.has(f) && existing.get(f)!.startsWith(GENERATED_MARK))
    .map((f) => `${SUPABASE_MIGRATIONS_DIR}/${f}`);
  // The lock records every file the directory will contain (append-only).
  const nextLock = Object.fromEntries([...want.keys()].sort().map((n) => [n, sha(want.get(n)!)]));
  const lockBody = `${JSON.stringify(nextLock, null, 2)}\n`;
  add(SUPABASE_LOCK, lockBody, existsSync(lockPath) ? readFileSync(lockPath, 'utf8') : undefined);
  return { writes, unchanged, orphans };
}
